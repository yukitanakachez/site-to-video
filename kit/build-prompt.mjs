#!/usr/bin/env node
// Builds the model's instructions from prompt.src.md by filling in the paths, the audio tool and the
// numbers that follow the pace in config/config.json (plan-second limits, narration words).
//   starwish: the job at /job, the agent at /agent, audio through the make-audio tool.
//   local:    the paths of a local run (local/run-job.mjs), audio through `node tools/make-audio`.
// Usage: node kit/build-prompt.mjs    writes prompt.md for starwish (test/build-prompt.test.mjs fails
// when prompt.md differs from what this writes now).
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { jobPaths } from '../lib/paths.mjs';
import { shotlistLimits } from '../lib/shotlist.mjs';
import paceLib from '../lib/pace.cjs';

const ROOT = fileURLToPath(new URL('..', import.meta.url));

export const GENERATED_LINE = '<!-- Generated by kit/build-prompt.mjs from prompt.src.md. Edit that, then run: node kit/build-prompt.mjs -->';

// Starwish passes the prompt and the request as one command-line argument, and Linux refuses one
// over 131,072 bytes (sibling DECISIONS.md, spawn E2BIG). This leaves room for the request.
export const PROMPT_BYTE_LIMIT = 100000;

const AUDIO_TOOL = {
  starwish: 'the `make-audio` tool (actions `voice`, `music`)',
  // The local tool takes positional arguments (tools/make-audio).
  local: '`run_command` with `node {{AGENT}}/tools/make-audio <action> …`, with `STARWISH_OUTPUT_DIR={{TOOL_OUTPUT}}/cN` for the Nth call '
    + '(c1, c2, …, a new folder for every call, failed ones too). The arguments are positional, in this order, each quoted: '
    + '`voice <voice_id> <text>`; `music <prompt> <seconds>`. For example: '
    + '`STARWISH_OUTPUT_DIR={{TOOL_OUTPUT}}/c1 node {{AGENT}}/tools/make-audio voice \'<voice_id>\' \'<text>\'`',
};

// The pace-dependent numbers, as the prompt prints them (lib/shotlist.mjs holds the rules).
// WORDS_AIM: the practical upper end, 42 words a 20 s video at normal speed (Task 12's measured
// voices), scaled by the pace. The example shot list is an 18 s video with a 2.5 s end card.
export function paceValues(pace = paceLib.pace()) {
  const L = shotlistLimits(pace);
  const n = (x) => String(Math.round(x * 100) / 100);
  const d1 = (x) => String(Math.round(x * 10) / 10);
  return {
    PACE: n(pace), PLAN_MIN: n(L.minDuration), PLAN_MAX: n(L.maxDuration),
    ENDCARD_MIN: n(L.minEndcard), ENDCARD_MAX: n(L.maxEndcard), END_MARGIN: n(L.endMargin),
    WORDS_MIN: n(L.minWords), WORDS_MAX: n(L.maxWords), WORDS_AIM: n(Math.round(42 * pace)),
    FOUR_PLAN_SEC: (4 / pace).toFixed(1),
    EXAMPLE_DURATION: d1(18 * pace), EXAMPLE_ENDCARD_START: d1(18 * pace - 2.5 * pace),
  };
}

// paths: { job, work, output, toolOutput, agent, kit }, as lib/paths.mjs gives them.
export function buildPrompt({ target, paths, pace } = {}) {
  if (!AUDIO_TOOL[target]) throw new Error(`target must be starwish or local, got ${target}`);
  const p = target === 'starwish' ? jobPaths({}) : paths;
  if (!p) throw new Error('a local prompt needs paths');
  const values = { JOB: p.job, WORK: p.work, OUTPUT: p.output, TOOL_OUTPUT: p.toolOutput, KIT: p.kit, AGENT: p.agent, ...paceValues(pace) };
  const src = readFileSync(join(ROOT, 'prompt.src.md'), 'utf8').replaceAll('{{AUDIO_TOOL}}', AUDIO_TOOL[target]);
  const text = src.replace(/\{\{([A-Z_]+)\}\}/g, (m, key) => {
    if (typeof values[key] !== 'string') throw new Error(`no value for ${m}`);
    return values[key];
  });
  return `${GENERATED_LINE}\n${text}`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = buildPrompt({ target: 'starwish' });
  const bytes = Buffer.byteLength(text, 'utf8');
  writeFileSync(join(ROOT, 'prompt.md'), text);
  console.log(`Wrote prompt.md (${bytes} bytes)${bytes > PROMPT_BYTE_LIMIT ? `: over the ${PROMPT_BYTE_LIMIT}-byte limit` : ''}`);
}
